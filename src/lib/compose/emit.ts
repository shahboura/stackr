import { stringify as stringifyYaml } from 'yaml';
import { GLOBAL_VARS } from '../catalog/vars';
import type { Service } from '../catalog/parse';
import { isSecret, SECRET_NOTES, type SecretKind } from '../secrets/generate';

export type VarKind = 'global' | 'port' | 'secret';

export type VarType = 'text' | 'number' | 'octal' | 'path' | 'port' | SecretKind;

export type ResolvedVar = {
	name: string;
	value: string;
	kind: VarKind;
	/** Service that owns ports and secrets. */
	slug?: string;
	secretKind?: SecretKind;
	/** Provenance for the environment table. */
	type: VarType;
	defaultValue: string;
	required: boolean;
};

export type BuildInput = {
	services: Service[];
	/** Global and port values. Missing ports fall back to the frontmatter defaults. */
	values: Record<string, string>;
	/** One entry per generator variable; values are never made up downstream. */
	secrets: Record<string, string>;
};

export type BuildResult = {
	compose: string;
	env: string;
	vars: ResolvedVar[];
};

const isRecord = (v: unknown): v is Record<string, unknown> =>
	typeof v === 'object' && v !== null && !Array.isArray(v);

function invalid(message: string): never {
	throw new Error(`compose: ${message}`);
}

export function resolveVars(input: BuildInput): ResolvedVar[] {
	const { services, values, secrets } = input;
	const resolved: ResolvedVar[] = [];
	const seen = new Map<string, ResolvedVar>();

	for (const service of services) {
		for (const name of service.vars) {
			const existing = seen.get(name);
			if (existing) continue;

			const secretKind = service.generators[name];
			if (secretKind) {
				const value = secrets[name];
				if (!value) invalid(`${name} needs a generated value`);
				if (!isSecret(secretKind, value)) {
					invalid(`${name} is not a valid ${secretKind} value`);
				}
				const entry: ResolvedVar = {
					name,
					value,
					kind: 'secret',
					slug: service.slug,
					secretKind,
					type: secretKind,
					defaultValue: '—',
					required: true
				};
				seen.set(name, entry);
				resolved.push(entry);
				continue;
			}

			const portDefault = service.portDefaults[name];
			if (portDefault !== undefined) {
				const raw = String(values[name] ?? portDefault);
				const port = Number(raw);
				if (!Number.isInteger(port) || port < 1 || port > 65535) {
					invalid(`${name} must be a port between 1 and 65535 (got "${raw}")`);
				}
				const entry: ResolvedVar = {
					name,
					value: String(port),
					kind: 'port',
					slug: service.slug,
					type: 'port',
					defaultValue: String(portDefault),
					required: true
				};
				seen.set(name, entry);
				resolved.push(entry);
				continue;
			}

			const global = GLOBAL_VARS[name];
			if (!global) invalid(`\${${name}} cannot be resolved`);
			const value = String(values[name] ?? global.defaultValue);
			if (value.trim() === '') invalid(`${name} cannot be empty`);
			const entry: ResolvedVar = {
				name,
				value,
				kind: 'global',
				type: global.kind,
				defaultValue: global.defaultValue,
				required: true
			};
			seen.set(name, entry);
			resolved.push(entry);
		}
	}

	return resolved;
}

function mergeCompose(services: Service[]): Record<string, unknown> {
	const merged: Record<string, unknown> = {};
	const extra: Record<string, Record<string, unknown>> = {};

	for (const service of services) {
		for (const [key, value] of Object.entries(service.compose)) {
			if (key === 'services') {
				if (!isRecord(value)) invalid(`${service.slug}: services is not a map`);
				for (const [name, definition] of Object.entries(value)) {
					if (name in merged) invalid(`two selected services both define "${name}"`);
					merged[name] = definition;
				}
				continue;
			}
			if (!isRecord(value)) invalid(`${service.slug}: unsupported top-level key "${key}"`);
			extra[key] ??= {};
			for (const [name, definition] of Object.entries(value)) {
				if (name in extra[key]) invalid(`two selected services both define ${key}.${name}`);
				extra[key][name] = definition;
			}
		}
	}

	return { services: merged, ...extra };
}

const BANNER = `# Generated by stackr. Keep this file next to .env, then run: docker compose up -d
# Values are read from .env in the same folder. Do not commit that file.
`;

export function buildCompose(services: Service[]): string {
	const yaml = stringifyYaml(mergeCompose(services), { lineWidth: 0 });
	return `${BANNER}\n${yaml}`;
}

/**
 * .env values are unquoted whenever the format allows it; paths with spaces or
 * `#` get double quotes so Compose reads the whole value.
 */
function envValue(value: string): string {
	if (/^[A-Za-z0-9_./:@%+=,-]+$/.test(value)) return value;
	return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

const groupTitle = (service: Service): string => service.name;

export function buildEnv(services: Service[], vars: ResolvedVar[]): string {
	const lines: string[] = [
		'# Generated by stackr — real values, not placeholders.',
		'# This file holds secrets. Keep it next to compose.yaml; do not commit it.',
		''
	];

	const globals = vars.filter((v) => v.kind === 'global');
	if (globals.length > 0) {
		lines.push('# ---- stack-wide ----');
		for (const v of globals) lines.push(`${v.name}=${envValue(v.value)}`);
		lines.push('');
	}

	for (const [index, service] of services.entries()) {
		const owned = vars.filter((v) => v.slug === service.slug);
		if (owned.length === 0) continue;
		lines.push(`# ---- ${groupTitle(service)} ----`);
		for (const v of owned) {
			if (v.kind === 'secret' && v.secretKind) {
				lines.push(`# ${v.name}: ${SECRET_NOTES[v.secretKind]}`);
			}
			lines.push(`${v.name}=${envValue(v.value)}`);
		}
		if (index < services.length - 1) lines.push('');
	}

	while (lines[lines.length - 1] === '') lines.pop();
	return `${lines.join('\n')}\n`;
}

export function buildFiles(input: BuildInput): BuildResult {
	const vars = resolveVars(input);
	return {
		compose: buildCompose(input.services),
		env: buildEnv(input.services, vars),
		vars
	};
}
