import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { loadCatalogFromDisk } from '../src/lib/catalog/node';

type ImageCheck = {
	image: string;
	resolves: boolean;
	arm64: boolean;
	error?: string;
};

type InspectOptions = {
	run?: (image: string) => string;
	attempts?: number;
	delayMs?: number;
};

const sleep = (ms: number) => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);

function runInspect(image: string): string {
	return execFileSync('docker', ['manifest', 'inspect', image], {
		encoding: 'utf8',
		stdio: ['ignore', 'pipe', 'pipe'],
		timeout: 60_000
	});
}

// Registry hiccups (rate limits, DNS) are transient; a real missing tag fails fast on every attempt.
function failureReason(cause: unknown): string {
	const stderr = (cause as { stderr?: unknown })?.stderr;
	const text =
		typeof stderr === 'string' && stderr.trim()
			? stderr
			: cause instanceof Error
				? cause.message
				: String(cause);
	return text.split('\n').filter(Boolean).pop()!.slice(0, 200);
}

export function inspect(image: string, options: InspectOptions = {}): ImageCheck {
	const { run = runInspect, attempts = 3, delayMs = 3_000 } = options;
	let error = '';
	for (let attempt = 1; attempt <= attempts; attempt++) {
		try {
			const manifest = JSON.parse(run(image)) as {
				manifests?: { platform?: { architecture?: string } }[];
				architecture?: string;
			};
			const archs = manifest.manifests?.map((entry) => entry.platform?.architecture) ?? [];
			const arm64 = archs.length > 0 ? archs.includes('arm64') : manifest.architecture === 'arm64';
			return { image, resolves: true, arm64 };
		} catch (cause) {
			error = failureReason(cause);
			if (attempt < attempts) sleep(delayMs);
		}
	}
	return { image, resolves: false, arm64: false, error };
}

function main() {
	const images = [...new Set(loadCatalogFromDisk().flatMap((service) => service.images))].sort();
	const results = images.map((image) => inspect(image));

	if (results.every((result) => !result.resolves)) {
		console.error('No image could be inspected. Is Docker available?');
		process.exit(1);
	}

	const problems = results.filter((result) => !result.resolves || !result.arm64);
	const report = [
		'<!-- Generated by scripts/check-images.ts. The weekly workflow opens a PR when this file changes. -->',
		'# Image check',
		'',
		'Every image referenced by `catalog/services/*/compose.yml`, checked with `docker manifest inspect`.',
		'',
		'| Image | Tag resolves | linux/arm64 |',
		'| --- | --- | --- |',
		...results.map(
			(result) => `| \`${result.image}\` | ${result.resolves ? 'yes' : 'no'} | ${result.arm64 ? 'yes' : 'no'} |`
		),
		'',
		problems.length === 0
			? 'All images resolve and publish a linux/arm64 manifest.'
			: [
					'## Problems',
					'',
					...problems.map(
						(result) =>
							`- \`${result.image}\`: ${result.resolves ? 'no linux/arm64 manifest' : `tag does not resolve (${result.error})`}`
					)
				].join('\n'),
		''
	].join('\n');

	const path = process.env.REPORT_PATH ?? 'reports/image-check.md';
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, report);
	console.log(report);
}

if ((import.meta as { main?: boolean }).main) main();
